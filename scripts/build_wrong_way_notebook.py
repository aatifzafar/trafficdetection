                "## 2. Define Model Architecture & Kinematic Feature Extractor\n",
                "The model takes rolling trajectory sequences $[(x_1, y_1), \\dots, (x_T, y_T)]$ and computes normalized kinematics: displacement, angle deviation $\\theta$, $\\cos(\\theta)$, $\\sin(\\theta)$, velocity, and heading drift."
